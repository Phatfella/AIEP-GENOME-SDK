"""
aiep_genome.adopt — Retrofit an existing project to the AIEP GENOME standard
==============================================================================
Implements the `aiep-genome adopt` command.

What it does
------------
1. Detects the existing project structure (Python package, Node.js, or generic).
2. Creates a `genome/` integration layer inside the main package.
3. Writes `.aiep-genome.json` configuration.
4. Generates `tests/test_genome_compliance.py` compliance test suite.
5. Updates or annotates `pyproject.toml` / `requirements.txt` with the genome dep.
6. Reports what was added and what manual steps are still needed.

Usage (CLI)
-----------
    aiep-genome adopt                        # auto-detect, apply to cwd
    aiep-genome adopt --pattern governance   # choose integration pattern
    aiep-genome adopt --dry-run              # preview changes without writing
    aiep-genome adopt --force                # overwrite existing genome/ files
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Literal


ADOPTION_PATTERN = Literal["auto", "evidence-ledger", "mirror", "governance", "bare"]


# ── Detection helpers ─────────────────────────────────────────────────────────

def _detect_package_name(target: Path) -> str | None:
    """Try to discover package name from pyproject.toml, setup.cfg, or setup.py."""
    for candidate in ("pyproject.toml", "setup.cfg", "setup.py"):
        f = target / candidate
        if not f.exists():
            continue
        text = f.read_text(encoding="utf-8", errors="replace")
        m = re.search(r'name\s*=\s*["\']([^"\']+)["\']', text)
        if m:
            return m.group(1)
    return target.name


def _detect_main_src_dir(target: Path, package_name: str) -> Path | None:
    """Locate the main Python source directory."""
    module_name = package_name.replace("-", "_")
    candidates = [
        target / "src" / module_name,
        target / module_name,
        target / "src" / package_name,
    ]
    for c in candidates:
        if c.is_dir():
            return c
    # Fallback: any dir under src/ that contains __init__.py
    src = target / "src"
    if src.is_dir():
        for d in src.iterdir():
            if d.is_dir() and (d / "__init__.py").exists():
                return d
    return None


def _detect_pattern(target: Path) -> str:
    """Heuristically detect the best adoption pattern for the project."""
    all_py = list(target.rglob("*.py"))
    all_text = "".join(
        f.read_text(encoding="utf-8", errors="replace")
        for f in all_py[:40]
    )
    if any(k in all_text for k in ("mirror_policy", "well-known", "aiep-manifest", "aiep_mirror")):
        return "mirror"
    if any(k in all_text for k in ("arbitration", "plausibility", "dissent", "GoalVector")):
        return "governance"
    if any(k in all_text for k in ("evidence", "ledger", "provenance", "commitment")):
        return "evidence-ledger"
    return "bare"


def _has_genome_dep(target: Path) -> bool:
    """Return True if aiep-genome-sdk already in pyproject.toml or requirements.txt."""
    for candidate in ("pyproject.toml", "requirements.txt", "requirements-dev.txt"):
        f = target / candidate
        if f.exists() and "aiep-genome" in f.read_text(encoding="utf-8", errors="replace"):
            return True
    return False


