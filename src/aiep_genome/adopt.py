def _genome_ledger() -> str:
    return '''\
"""
genome/ledger.py — Append-only Evidence Ledger for this project.
Generated by aiep-genome adopt. Extend but do not modify kernel primitives.
"""
from __future__ import annotations

from aiep_genome.kernel import (
    canonical_json, sha256_hex, evidence_commitment,
    lifecycle_hash, pack_hash, evaluate_gate, GateResult,
)

SCHEMA_VERSION_ID = "aiep.evidence.v1.0.0"


class EvidenceLedger:
    """
    Append-only, cryptographically anchored evidence ledger.

    Usage::

        ledger = EvidenceLedger()
        ec = ledger.commit({"source": "api", "value": 42}, provenance="system-a")
        gate = ledger.gate(ec)
        assert gate.is_open

    This class is the integration point between your application\'s domain data
    and the AIEP GENOME kernel. You should instantiate this once per service
    context or once per request boundary, depending on your architecture.
    """

    def __init__(self):
        self._evidence: dict[str, dict] = {}
        self._reasoning: list[dict] = []
        self._active_branches: set[str] = set()

    def commit(
        self,
        data: dict,
        provenance: str,
        permitted_use_scope: str = "UNRESTRICTED",
        retention_policy_id: str = "retain-7-years",
        expiry_ts: str = "",
    ) -> str:
        """Commit evidence. Returns evidence_commitment hash."""
        canon = canonical_json(data)
        ec = evidence_commitment(canon, provenance, SCHEMA_VERSION_ID)
        lh = lifecycle_hash(ec, permitted_use_scope, retention_policy_id, expiry_ts, SCHEMA_VERSION_ID)
        self._evidence[ec] = {
            "content_hash": sha256_hex(canon),
            "evidence_commitment": ec,
            "lifecycle_hash": lh,
            "provenance": provenance,
        }
        return ec

    def gate(self, evidence_hash: str, branch_id: str = "", operation_label: str = "") -> GateResult:
        """Evaluate gate invariants I1–I5."""
        return evaluate_gate(
            evidence_hash, self._evidence, self._reasoning,
            self._active_branches, branch_id=branch_id, operation_label=operation_label,
        )

    def replay_hash(self) -> str:
        """I6: Deterministic replay pack hash."""
        return pack_hash(list(self._evidence.values()), self._reasoning, SCHEMA_VERSION_ID)

    def export(self) -> dict:
        return {
            "evidence": dict(self._evidence),
            "reasoning": list(self._reasoning),
            "replay_hash": self.replay_hash(),
            "schema_version_id": SCHEMA_VERSION_ID,
        }
'''


