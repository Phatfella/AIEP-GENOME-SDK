def _genome_governance() -> str:
    return '''\
"""
genome/governance.py — Constitutional arbitration layer.
Generated by aiep-genome adopt. Extend but do not modify kernel primitives.
"""
from __future__ import annotations

from aiep_genome.kernel import (
    canonical_json, sha256_hex,
    arbitration_hash, evaluate_admissibility,
    CONSTITUTIONAL_CONSTRAINTS,
)

SCHEMA_VERSION_ID = "aiep.governance.v1.0.0"


def make_arbitration_record(
    branch_id: str,
    conclusion: dict,
    plausibility_status: str,
    dissent_final_position: str,
    gate_status: str,
) -> dict:
    admissible, reason = evaluate_admissibility(
        plausibility_status, dissent_final_position, gate_status
    )
    if not admissible:
        raise ValueError(f"Conclusion inadmissible: {reason}")
    conclusion_hash = sha256_hex(canonical_json(conclusion))
    ah = arbitration_hash(branch_id, conclusion_hash, True, plausibility_status, SCHEMA_VERSION_ID)
    return {
        "arbitration_hash": ah,
        "branch_id": branch_id,
        "conclusion_hash": conclusion_hash,
        "admissible": admissible,
        "schema_version_id": SCHEMA_VERSION_ID,
    }
'''


def _compliance_tests(package_name: str, pattern: str, genome_path: str) -> str:
    return f'''\
"""
tests/test_genome_compliance.py — Genome compliance tests for {package_name}
Generated by aiep-genome adopt. Review and extend, do not delete.

These tests verify that the genome integration layer is correctly wired
and that kernel determinism is preserved in this deployment.
"""
import unittest
from aiep_genome.kernel import run_self_test, canonical_json, sha256_hex, concat_hash


class TestKernelComplianceBaseline(unittest.TestCase):
    """Kernel invariants — must always pass regardless of pattern."""

    def test_kernel_self_test(self):
        self.assertTrue(run_self_test())

    def test_r1_key_ordering(self):
        self.assertEqual(canonical_json({{"z": 1, "a": 2}}), \'{{"a":2,"z":1}}\')

    def test_r3_unicode_nfc(self):
        composed = "\\u00c5"
        decomposed = "A\\u030a"
        self.assertEqual(canonical_json({{"n": composed}}), canonical_json({{"n": decomposed}}))

    def test_r7_boundary_safety(self):
        self.assertNotEqual(concat_hash("ab", "c"), concat_hash("a", "bc"))

    def test_known_sha256_vector(self):
        self.assertEqual(
            sha256_hex(""),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
        )

    def test_genome_module_importable(self):
        import importlib
        genome = importlib.import_module("{genome_path}")
        self.assertIsNotNone(genome)
'''


def _adoption_config(package_name: str, pattern: str, genome_dir: str) -> dict:
    return {
        "name": package_name,
        "module": package_name.replace("-", "_"),
        "genome_sdk_version": "1.2.0",
        "kernel_version": "1.0.0",
        "lockfile_version": "1.0.0",
        "pattern": pattern,
        "genome_dir": genome_dir,
        "adoption_mode": "adopt",
        "schema_version_id": f"aiep.{pattern.replace('-', '_')}.v1.0.0",
    }


# ── Dependency patching ───────────────────────────────────────────────────────

def _add_genome_dep_to_pyproject(pyproject_path: Path) -> bool:
    """
    Add aiep-genome-sdk to dependencies in pyproject.toml.
    Returns True if file was modified.
    """
    if not pyproject_path.exists():
        return False
    text = pyproject_path.read_text(encoding="utf-8")
    if "aiep-genome-sdk" in text:
        return False  # already present

    # Find dependencies = [ ... ] and add to it
    new_text = re.sub(
        r'(dependencies\s*=\s*\[)',
        r'\1\n    "aiep-genome-sdk>=1.2.0",',
        text,
        count=1,
    )
    if new_text != text:
        pyproject_path.write_text(new_text, encoding="utf-8")
        return True

    # No dependencies array found — append a note to the file
    with open(pyproject_path, "a", encoding="utf-8") as f:
        f.write('\n# TODO: add aiep-genome-sdk>=1.2.0 to your [project] dependencies\n')
    return True


# ── Main adopt function ───────────────────────────────────────────────────────

@dataclass
class AdoptResult:
    package_name: str
    genome_dir: str
    pattern: str
    created: list = field(default_factory=list)
    skipped: list = field(default_factory=list)
    manual_steps: list = field(default_factory=list)
    warnings: list = field(default_factory=list)

    @property
    def success(self) -> bool:
        return True

    # Convenience aliases
    @property
    def ok(self) -> bool:
        return True

    @property
    def created_files(self) -> list:
        return self.created


def adopt_project(
    target_dir: str | Path = ".",
    *,
    pattern: str = "auto",
    dry_run: bool = False,
    force: bool = False,
) -> AdoptResult:
    """
    Retrofit an existing project to the AIEP GENOME standard.

    Parameters
    ----------
    target_dir  : Root of the existing project [cwd].
    pattern     : Integration pattern — auto | evidence-ledger | mirror | governance | bare.
    dry_run     : Preview only — do not write any files.
    force       : Overwrite existing genome/ files.
    """
    target = Path(target_dir).resolve()
    package_name = _detect_package_name(target) or target.name
    src_dir = _detect_main_src_dir(target, package_name)

    if pattern is None or pattern == "auto":
        pattern = _detect_pattern(target)

    # Determine where to create genome/
    if src_dir:
        genome_dir = src_dir / "genome"
        genome_module = f"{src_dir.name}.genome"
        tests_dir = target / "tests"
    else:
        # No Python package found — create at project root
        genome_dir = target / "genome"
        genome_module = "genome"
        tests_dir = target / "tests"

    result = AdoptResult(
        package_name=package_name,
        genome_dir=str(genome_dir.relative_to(target)),
        pattern=pattern,
    )

    def write(path: Path, content: str) -> None:
        rel = str(path.relative_to(target))
        if path.exists() and not force:
            result.skipped.append(rel)
            return
        if not dry_run:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
        result.created.append(rel)

    def write_json(path: Path, data: dict) -> None:
        write(path, json.dumps(data, indent=2) + "\n")

    # ── genome/ integration layer ────────────────────────────────────────────
    write(genome_dir / "__init__.py", _genome_init())
    write(genome_dir / "canon.py", _genome_canon())

    if pattern in ("evidence-ledger", "governance"):
        write(genome_dir / "ledger.py", _genome_ledger())
    if pattern == "mirror":
        write(genome_dir / "mirror.py", _genome_mirror())
    if pattern == "governance":
        write(genome_dir / "governance.py", _genome_governance())

    # ── Config ──────────────────────────────────────────────────────────────
    cfg_path = target / ".aiep-genome.json"
    rel_genome = str(genome_dir.relative_to(target)).replace("\\", "/")
    write_json(cfg_path, _adoption_config(package_name, pattern, rel_genome))

    # ── Compliance tests ─────────────────────────────────────────────────────
    tests_dir.mkdir(parents=True, exist_ok=True)
    test_path = tests_dir / "test_genome_compliance.py"
    write(test_path, _compliance_tests(package_name, pattern, genome_module))

    # ── Dependency patching ──────────────────────────────────────────────────
    pyproject_path = target / "pyproject.toml"
    if not dry_run and pyproject_path.exists() and not _has_genome_dep(target):
        modified = _add_genome_dep_to_pyproject(pyproject_path)
        if modified:
            result.created.append("pyproject.toml (aiep-genome-sdk dep added)")
    elif not pyproject_path.exists():
        result.manual_steps.append(
            "Add  aiep-genome-sdk>=1.2.0  to your project dependencies "
            "(pip install aiep-genome-sdk, or add to requirements.txt)"
        )

    # ── Manual steps ─────────────────────────────────────────────────────────
    if not (target / "tests" / "__init__.py").exists():
        result.manual_steps.append(
            "Create tests/__init__.py  (or ensure your test runner can find tests/)"
        )

    result.manual_steps.append(
        f"Review {rel_genome}/ — extend the generated layer with your domain logic"
    )
    result.manual_steps.append("Run:  pytest  to confirm compliance tests pass")

    if not _has_genome_dep(target):
        result.manual_steps.append("Install genome SDK:  pip install aiep-genome-sdk>=1.2.0")

    return result
