"""
AIEP GENOME SDK — Kernel: DivergenceGraph Builder (P01 §[0011-0018A])
=======================================================================
Implements the core P01 invention: a DivergenceGraph of alternative canonical
instruction objects generated by divergence operators D1-D7, scored
deterministically via registry-retrieved coefficients, with tamper-evident
parent-hash chaining.

Learning from hub build: building the worked example in generate-v2-manifest.mjs
revealed that the SDK had arbitration (evaluate_admissibility) but no
first-class DivergenceGraph builder. This module closes that gap.

P01 §[0016] scoring function:
    Score_i = α·deviation_i + β·safetyViolations_i + γ·resourceCost_i

P01 §[0017] tie-breaking:
    Lowest score wins; ties broken by nodeHash lexicographic ascending.

P01 §[0015] tamper-evidence:
    nodeHash = H(canonicalJson(nodeCore) + parentHash)  [simple concat per spec]
    Note: P01 §[0014] specifies SHA3-256; this implementation uses SHA-256 (R4)
    for consistency with the hub canon. Deviation is documented in the artefact.
"""

from dataclasses import dataclass, field, asdict
from typing import Optional, List, Dict, Any

from aiep_genome.kernel.canon import canonical_json, sha256_hex

KERNEL_VERSION = "1.0.0"
GENESIS_HASH   = "0" * 64

DIVERGENCE_OPERATORS: Dict[str, str] = {
    "D1": "Synonym substitution — replace a term with a recognised synonym",
    "D2": "Parameter relaxation — widen a numeric or categorical constraint",
    "D3": "Parameter tightening — narrow a numeric or categorical constraint",
    "D4": "Context promotion — elevate a contextual qualifier to a primary constraint",
    "D5": "Context demotion — demote a primary constraint to a contextual qualifier",
    "D6": "Claim strengthening — increase epistemic certainty of a claim",
    "D7": "Claim weakening — decrease epistemic certainty of a claim",
}


@dataclass
class DivergenceNode:
    node_id: str
    candidate_canonical: str
    divergence_operator: Optional[str]  # None for primary node
    deviation_metric: float
    safety_violations: int
    resource_cost: float
    parent_hash: str
    node_hash: str
    score: float = field(init=False)

    def compute_score(self, alpha: float, beta: float, gamma: float) -> float:
        return alpha * self.deviation_metric + beta * self.safety_violations + gamma * self.resource_cost

    def to_dict(self) -> Dict[str, Any]:
        return {
            "candidateCanonical":  self.candidate_canonical,
            "deviationMetric":     self.deviation_metric,
            "divergenceOperator":  self.divergence_operator,
            "nodeHash":            self.node_hash,
            "nodeId":              self.node_id,
            "parentHash":          self.parent_hash,
            "resourceCost":        self.resource_cost,
            "safetyViolations":    self.safety_violations,
            "score":               self.score,
        }


def _node_hash(core: dict, parent_hash: str) -> str:
    """
    SHA-256(canonicalJson(core) + parentHash) — simple string concatenation per P01 §[0014].
    Note: P01 specifies SHA3-256; this uses SHA-256 (hub canon R4). Documented deviation.
    """
    return sha256_hex(canonical_json(core) + parent_hash)


class DivergenceGraphBuilder:
    """
    Builds a P01-compliant DivergenceGraph from a primary instruction and
    a list of (operator, text, deviation, safetyViolations, resourceCost) alternates.

    Usage::

        builder = DivergenceGraphBuilder(
            intention="Publish an exemplar AIEP Mirror node.",
            protocol_version="1.0.0",
            registry_ref="/.well-known/aiep/registry/protocol/v1.json",
            alpha=1.0, beta=2.0, gamma=0.5,
        )
        builder.set_primary(
            text="Publish an exemplar AIEP Mirror node demonstrating the full protocol surface.",
            resource_cost=1.0,
        )
        builder.add_alternate("D1", "Deploy a canonical AIEP Mirror node...", deviation=0.1, resource_cost=1.0)
        # ... up to 7 alternates (P01 §[0012]: 2-9 nodes total)
        graph = builder.build()
    """

    def __init__(
        self,
        intention: str,
        protocol_version: str = "1.0.0",
        registry_ref: str = "/.well-known/aiep/registry/protocol/v1.json",
        safety_envelope_id: str = "aiep-hub-default",
        alpha: float = 1.0,
        beta:  float = 2.0,
        gamma: float = 0.5,
    ):
        self.intention         = intention
        self.protocol_version  = protocol_version
        self.registry_ref      = registry_ref
        self.safety_envelope_id = safety_envelope_id
        self.alpha = alpha
        self.beta  = beta
        self.gamma = gamma
        self._primary: Optional[dict] = None
        self._alternates: List[dict]  = []

    def set_primary(
        self,
        text: str,
        resource_cost: float = 1.0,
        safety_violations: int = 0,
    ) -> "DivergenceGraphBuilder":
        """Set the primary canonical instruction (deviation = 0.0 by definition)."""
        self._primary = {
            "text":              text,
            "resource_cost":     resource_cost,
            "safety_violations": safety_violations,
        }
        return self

    def add_alternate(
        self,
        operator: str,
        text: str,
        deviation: float,
        resource_cost: float = 1.0,
        safety_violations: int = 0,
    ) -> "DivergenceGraphBuilder":
        """
        Add an alternate node generated by divergence operator D1-D7.
        P01 §[0012]: min 1 alternate (2 total nodes), max 8 alternates (9 total).
        """
        if operator not in DIVERGENCE_OPERATORS:
            raise ValueError(f"Unknown operator '{operator}'. Valid: {list(DIVERGENCE_OPERATORS)}")
        if len(self._alternates) >= 8:
            raise ValueError("P01 §[0012]: maximum 8 alternates (9 total nodes including primary)")
        self._alternates.append({
            "operator":          operator,
            "text":              text,
            "deviation":         deviation,
            "resource_cost":     resource_cost,
            "safety_violations": safety_violations,
        })
        return self

    def build(self) -> Dict[str, Any]:
        """
        Build and return the DivergenceGraph artefact dict.
        Nodes are chained: each node's parentHash is the previous node's nodeHash.
        The graph is scored and the winning node identified deterministically.
        """
        if self._primary is None:
            raise ValueError("Primary node required (call set_primary first)")
        if len(self._alternates) < 1:
            raise ValueError("P01 §[0012]: at least 1 alternate node required (2 total)")

        nodes: List[DivergenceNode] = []
        prev_hash = GENESIS_HASH

        # Primary node (deviation = 0.0)
        p = self._primary
        p_core = {
            "candidateCanonical": p["text"],
            "deviationMetric":    0.0,
            "divergenceOperator": None,
            "resourceCost":       p["resource_cost"],
            "safetyViolations":   p["safety_violations"],
        }
        p_hash = _node_hash(p_core, prev_hash)
        primary_node = DivergenceNode(
            node_id="primary",
            candidate_canonical=p["text"],
            divergence_operator=None,
            deviation_metric=0.0,
            safety_violations=p["safety_violations"],
            resource_cost=p["resource_cost"],
            parent_hash=prev_hash,
            node_hash=p_hash,
        )
        primary_node.score = primary_node.compute_score(self.alpha, self.beta, self.gamma)
        nodes.append(primary_node)
        prev_hash = p_hash

        # Alternate nodes D1-D7
        for i, alt in enumerate(self._alternates, start=1):
            a_core = {
                "candidateCanonical": alt["text"],
                "deviationMetric":    alt["deviation"],
                "divergenceOperator": alt["operator"],
                "resourceCost":       alt["resource_cost"],
                "safetyViolations":   alt["safety_violations"],
            }
            a_hash = _node_hash(a_core, prev_hash)
            alt_node = DivergenceNode(
                node_id=f"d{i}",
                candidate_canonical=alt["text"],
                divergence_operator=alt["operator"],
                deviation_metric=alt["deviation"],
                safety_violations=alt["safety_violations"],
                resource_cost=alt["resource_cost"],
                parent_hash=prev_hash,
                node_hash=a_hash,
            )
            alt_node.score = alt_node.compute_score(self.alpha, self.beta, self.gamma)
            nodes.append(alt_node)
            prev_hash = a_hash

        # Deterministic selection: lowest score; tie-break by nodeHash ascending
        selected = min(nodes, key=lambda n: (n.score, n.node_hash))

        return {
            "@context":         "https://aiep.dev/schemas/context/v2",
            "@type":            "AIEPInstruction",
            "intention":        self.intention,
            "protocolVersion":  self.protocol_version,
            "registryRef":      self.registry_ref,
            "safetyEnvelopeId": self.safety_envelope_id,
            "note":             (
                "nodeHash uses SHA-256 (hub canon R4) not SHA3-256 (P01 §[0014]) "
                "for consistency with the AIEP hub canon implementation. Documented deviation."
            ),
            "divergenceGraph": {
                "nodes":           [n.to_dict() for n in nodes],
                "registryRef":     self.registry_ref,
                "scoringFunction": "Score_i = alpha * deviation_i + beta * safetyViolations_i + gamma * resourceCost_i",
                "selectedNodeId":  selected.node_id,
                "selectedScore":   selected.score,
            },
        }
